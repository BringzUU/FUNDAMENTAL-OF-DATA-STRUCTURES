    private void setupTable() {
        // Define column headers
        String[] columnNames = {"Code", "Model", "Brand", "Price", "Year", "Type"};
        tableModel = new DefaultTableModel(columnNames, 0);
        jTable1.setModel(tableModel);
    }

    private void generateInitialData() {
        // Generate 10 random cars as per assignment
        for (int i = 0; i < 10; i++) {
            carArray.addLast(generateRandomCar());
        }
    }

    private void refreshTable() {
        // Clear existing rows
        tableModel.setRowCount(0);
        
        // Add data from MyArray to the table
        for (Car car : carArray.getCars()) {
            Object[] rowData = {
                car.getCode(),
                car.getModel(),
                car.getBrand(),
                String.format("%,d", car.getPrice()), // Format price with commas
                car.getYear(),
                car.getType()
            };
            tableModel.addRow(rowData);
        }
    }

    public static Car generateRandomCar() {
        Random rand = new Random();
        
        // Data sources for random generation
        String[] brands = {"Honda", "Toyota", "Ford", "Volvo", "GWM"};
        String[] types = {"Gasoline", "Diesel", "Electric", "Hybrid"};
        String upperChars = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
        String digits = "0123456789";

        // Generate code: 2 uppercase letters + 3 digits
        String code = "" + upperChars.charAt(rand.nextInt(upperChars.length())) +
                      upperChars.charAt(rand.nextInt(upperChars.length())) +
                      digits.charAt(rand.nextInt(digits.length())) +
                      digits.charAt(rand.nextInt(digits.length())) +
                      digits.charAt(rand.nextInt(digits.length()));

        // Generate model: 4-10 chars, first letter uppercase
        int modelLength = rand.nextInt(7) + 4; // Length from 4 to 10
        StringBuilder modelBuilder = new StringBuilder();
        modelBuilder.append(upperChars.charAt(rand.nextInt(upperChars.length()))); // First char
        for (int i = 1; i < modelLength; i++) {
            modelBuilder.append(Character.toLowerCase(upperChars.charAt(rand.nextInt(upperChars.length()))));
        }
        String model = modelBuilder.toString();

        // Generate other fields
        String brand = brands[rand.nextInt(brands.length)];
        int price = rand.nextInt(9_500_001) + 500_000; // Range 500,000 to 10,000,000
        int year = rand.nextInt(26) + 2000; // Range 2000 to 2025
        String type = types[rand.nextInt(types.length)];

        return new Car(code, model, brand, price, year, type);
    }

